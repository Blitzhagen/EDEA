namespace EDEA;

/// <summary>
/// Specifies the view models that can be displayed inside the HUD window.
/// </summary>
public enum HudWindowTabViewModel
{
    /// <summary>Automatically select the current view model.</summary>
    Auto,

    /// <summary>Display the body table view model.</summary>
    BodyTableViewModel,

    /// <summary>Display the navigation route table view model.</summary>
    NavRouteTableViewModel
}
