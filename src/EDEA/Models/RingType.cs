namespace EDEA.Models;

/// <summary>
/// Identifies the composition type of a ring.
/// </summary>
public enum RingType
{
    /// <summary>
    /// The ring type is unknown.
    /// </summary>
    Unknown,

    /// <summary>
    /// A metal-rich ring.
    /// </summary>
    MetalRich,

    /// <summary>
    /// A metallic ring.
    /// </summary>
    Metallic,

    /// <summary>
    /// A rocky ring.
    /// </summary>
    Rocky,

    /// <summary>
    /// An icy ring.
    /// </summary>
    Icy
}
